const axios = require('axios');
const fs = require('fs');

const CONFIG_PATH = 'C:\\Users\\Asus\\.gemini\\config\\mcp_config.json';
const configStr = fs.readFileSync(CONFIG_PATH, 'utf8');
const env = JSON.parse(configStr).mcpServers['social-media-mcp'].env;

const message = `☕️ มือใหม่หัดดื่มกาแฟ สั่งอะไรดี? วันนี้ 'กาแฟสดท้ายรถ' มีคำตอบครับ! 📝

หลายคนอาจจะเคยยืนงงหน้าร้านกาแฟว่าแต่ละเมนูมันต่างกันยังไง วันนี้แอดมินขอสรุปให้ฟังแบบเข้าใจง่ายๆ เอาไปใช้สั่งได้เลยครับ! 

1️⃣ เอสเพรสโซ่ (Espresso) 🥃
กาแฟดำช็อตเข้มข้น เพียวๆ ไม่ผสมอะไรเลย (แต่ที่ไทยบางร้านจะมี 'เอสเพรสโซ่เย็น' ที่ใส่นมข้นหวาน อันนี้เป็นสูตรเฉพาะพี่ไทยเราครับ 🇹🇭)

2️⃣ อเมริกาโน่ (Americano) 🧊
สายรักสุขภาพต้องแก้วนี้! คือการเอาช็อตเอสเพรสโซ่มาผสมน้ำเปล่า ได้รสชาติกาแฟแท้ๆ แคลอรีต่ำ ดื่มแล้วตาสว่าง!

3️⃣ ลาเต้ (Latte) 🥛
ใครเพิ่งเริ่มดื่มกาแฟ แนะนำลาเต้เลยครับ เป็นกาแฟใส่นมเยอะๆ รสชาตินุ่มละมุน ดื่มง่ายสุดๆ

4️⃣ คาปูชิโน่ (Cappuccino) ☁️
คล้ายลาเต้ แต่จะมี 'ฟองนมนุ่มๆ' โปะอยู่ข้างบน กาแฟจะเข้มกว่าลาเต้นิดนึง ฟินสุดๆ 

5️⃣ มอคค่า (Mocha) 🍫
การผสมผสานที่ลงตัวระหว่าง 'กาแฟ' กับ 'ช็อกโกแลต' (หรือโกโก้) ดื่มง่าย หอม หวานกำลังดี!

ชอบดื่มแบบไหน แวะมาสั่งกันได้นะครับ! 
📍 พิกัด: ตลาดเช้า หน้าวัดบางวัว 
⏰ เปิดบริการทุกเช้า: 05:00 น. - 09:00 น.
แวะมารับความสดชื่นก่อนไปลุยงานกันนะครับ! ✌️🏭

#กาแฟสดหน้าวัดบางวัว #หนุ่มสาวโรงงาน #ตลาดเช้าวัดบางวัว #ความรู้เรื่องกาแฟ`;

async function post() {
  try {
    const res = await axios.post(`https://graph.facebook.com/v19.0/${env.FACEBOOK_PAGE_ID}/feed`, {
      message: message,
      access_token: env.FACEBOOK_ACCESS_TOKEN
    });
    console.log('SUCCESS:', res.data);
  } catch(e) {
    console.error('ERROR:', e.response ? e.response.data : e.message);
  }
}

post();
